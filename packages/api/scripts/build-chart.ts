import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const srcDir = join(import.meta.dir, '..', 'src', 'chart')
const built = await Bun.build({
  entrypoints: [join(srcDir, 'client.ts')],
  minify: true,
  format: 'iife',
  target: 'browser',
})
if (!built.success) throw new AggregateError(built.logs, 'Chart client build failed')
const js = await built.outputs[0].text()
const version = new Bun.CryptoHasher('sha256').update(js).digest('hex').slice(0, 8)
writeFileSync(
  join(srcDir, 'bundle.ts'),
  `// GENERATED by scripts/build-chart.ts.\nexport const CHART_JS = ${JSON.stringify(js)}\nexport const CHART_VERSION = ${JSON.stringify(version)}\n`,
)
console.log(`Chart bundle: ${js.length}B → v${version}`)
